"""Request and response schemas (these also drive the Swagger UI at /docs)."""

from typing import Any, Literal

from pydantic import BaseModel, Field, field_validator


class UploadResponse(BaseModel):
    document_id: str
    filename: str
    chunks_indexed: int
    replaced_existing: bool = Field(description="True if this document_id already existed and was re-indexed.")


class DocumentInfo(BaseModel):
    document_id: str
    filename: str
    chunks: int


class ChatMessage(BaseModel):
    role: Literal["user", "assistant"]
    content: str


class MessagesResponse(BaseModel):
    conversation_id: str
    messages: list[ChatMessage]


class CreateConversationRequest(BaseModel):
    title: str = Field(min_length=1, max_length=200, examples=["AI Research"])

    @field_validator("title")
    @classmethod
    def _strip(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("title must not be blank")
        return value


class ConversationResponse(BaseModel):
    conversation_id: str = Field(description="The id generated by NAMS.")
    title: str


class ExtractionStatusResponse(BaseModel):
    conversation_id: str
    state: Literal["pending", "completed", "failed", "unknown"]
    pending_messages: int
    summary: dict[str, int] = Field(description="NAMS' per-message extraction status counts.")


class ChatRequest(BaseModel):
    conversation_id: str = Field(min_length=1, max_length=128, examples=["actual-conversation-id"])
    message: str = Field(min_length=1, max_length=4000, examples=["Which project am I working on?"])

    @field_validator("message")
    @classmethod
    def _not_blank(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("message must not be blank")
        return value


class ChatResponse(BaseModel):
    answer: str
    conversation_id: str
    document_sources: list[str] = Field(
        description="Filenames of the document chunks retrieved and given to the model (empty if none)."
    )
    memory_retrieval_succeeded: bool = Field(
        description="False if NAMS long-term memory could not be queried. True with no entities means 'nothing found'."
    )
    memory_retrieval_status: Literal["ok", "empty", "unavailable"]
    memory_entities_used: list[dict[str, Any]] = Field(description="Entities from NAMS given to the model.")
    messages_saved: bool = Field(description="True if NAMS stored the user and assistant messages.")
    extraction_status: Literal["pending", "completed", "failed", "unknown", "not_checked"] = Field(
        description="State of NAMS' background entity extraction. 'pending' is normal right after saving."
    )
    warnings: list[str] = []


class MemorySearchResponse(BaseModel):
    query: str
    count: int
    results: list[dict[str, Any]]
    note: str | None = None


class HealthResponse(BaseModel):
    status: Literal["ok", "degraded"]
    chroma: dict[str, Any]
    nams: dict[str, Any]
    llm: dict[str, Any]
